#!/usr/bin/env bash
# Add multi-language docs to an already-built static package, so the editor's own
# language selector switches tutorials/docs as well as the UI.
#
# Run AFTER scripts/package_static_fetch_locs.sh has produced $OUT_DIR.
#
#
# The problem
# -----------
# In a static build pxt resolves a doc to a plain file path and puts the language in
# the QUERY STRING only (pxt-core `pxtapp.js`, markdownAsync, isStatic branch):
#
#     h = `docs/${path}.md`;                  // path never contains the language
#     if (lang != "en") p.set("lang", lang);  // -> /docs/foo.md?lang=de
#
# A static file server ignores `?lang=de` and returns the one English file. So simply
# dropping translated markdown into the package does nothing: nothing ever requests it.
#
# The approach
# ------------
# Ship the translations at a predictable path and rewrite the request in the page.
#
#   docs/_loc/<lang>/<page>.md      translated copy (missing -> English is used)
#
# pxt issues doc requests through XMLHttpRequest (Util.httpRequestCoreAsync builds an
# XHR, not fetch), so a tiny shim that wraps XMLHttpRequest.prototype.open is enough:
# it rewrites `/docs/<page>.md?lang=xx` to `/docs/_loc/xx/<page>.md` when that file
# exists, and otherwise leaves the request alone so English is served.
#
# Why not a service worker: pxt already registers its own at the root scope (it also
# drives WebUSB), only one worker can control a scope, and it is regenerated by every
# staticpkg run. Service workers also require a secure context, so a plain-HTTP host or
# file:// would silently fall back to English. The XHR shim has neither problem.
#
# Why not a custom server: this keeps the package servable by any static file host,
# which was the whole point of the packaged build.
#
#
# Usage:
#   scripts/package_static_multilang.sh de              # add German docs
#   scripts/package_static_multilang.sh de fr           # several
#   DOCS_SRC=../translated-docs scripts/package_static_multilang.sh de
#
# Translated markdown is taken from $DOCS_SRC/<lang>/**.md, mirroring the layout of
# docs/ (e.g. de/calliope/tutorials.md). Pages with no translation are simply omitted
# and fall back to English at runtime.
set -euo pipefail

cd "$(dirname "$0")/.."

LANGS=("$@")
if [ ${#LANGS[@]} -eq 0 ]; then
    echo "usage: $0 <lang> [lang...]   e.g. $0 de" >&2
    exit 2
fi

OUT_DIR="${OUT_DIR:-built/packaged}"
DOCS_SRC="${DOCS_SRC:-docs/_loc}"   # <lang>/<page>.md, mirroring docs/
SHIM="docs-lang-shim.js"

if [ ! -d "$OUT_DIR" ]; then
    echo "!!  $OUT_DIR not found - run scripts/package_static_fetch_locs.sh first" >&2
    exit 1
fi

# ---------------------------------------------------------------- copy translations
total=0
for lang in "${LANGS[@]}"; do
    src="$DOCS_SRC/$lang"
    dst="$OUT_DIR/docs/_loc/$lang"
    if [ ! -d "$src" ]; then
        echo "!!  no translated docs for '$lang' at $src -- skipping" >&2
        echo "    (create $src/<page>.md mirroring docs/, e.g. $src/calliope/tutorials.md)" >&2
        continue
    fi
    mkdir -p "$dst"
    # only markdown; images and other assets stay shared with the English tree
    (cd "$src" && find . -name '*.md' -print0) | while IFS= read -r -d '' f; do
        mkdir -p "$dst/$(dirname "$f")"
        cp "$src/$f" "$dst/$f"
    done
    n=$(find "$dst" -name '*.md' | wc -l)
    total=$((total + n))
    echo "==> $lang: $n translated page(s) -> $dst"
done

if [ "$total" -eq 0 ]; then
    echo "!!  nothing copied; not installing the shim" >&2
    exit 1
fi

# ------------------------------------------------------------------- build the shim
# The manifest lets the shim redirect only pages that actually have a translation, so
# an untranslated page keeps serving English instead of 404ing.
python3 - "$OUT_DIR" "$SHIM" "${LANGS[@]}" <<'PYEOF'
import json, os, sys

out, shim_name, langs = sys.argv[1], sys.argv[2], sys.argv[3:]
root = os.path.join(out, "docs", "_loc")

manifest = {}
for lang in langs:
    base = os.path.join(root, lang)
    if not os.path.isdir(base):
        continue
    pages = []
    for dirpath, _, files in os.walk(base):
        for f in files:
            if f.endswith(".md"):
                rel = os.path.relpath(os.path.join(dirpath, f), base)
                pages.append(rel.replace(os.sep, "/"))
    if pages:
        manifest[lang] = sorted(pages)

shim = """// Injected by scripts/package_static_multilang.sh -- do not edit by hand.
//
// pxt asks for docs as `/docs/<page>.md?lang=xx` and a static file server ignores the
// query string, so every language would get the English file. pxt issues these through
// XMLHttpRequest (Util.httpRequestCoreAsync), so wrapping open() is enough to redirect
// them to the translated copy -- but only for pages that actually have one, so anything
// untranslated transparently falls back to English.
(function () {
  var PAGES = __MANIFEST__;
  var open = XMLHttpRequest.prototype.open;
  XMLHttpRequest.prototype.open = function (method, url) {
    try {
      if (typeof url === "string" && url.indexOf("/docs/") !== -1 && url.indexOf("lang=") !== -1) {
        var q = url.indexOf("?");
        var path = q < 0 ? url : url.slice(0, q);
        var qs = q < 0 ? "" : url.slice(q + 1);
        var m = /(?:^|&)lang=([^&]+)/.exec(qs);
        var lang = m && decodeURIComponent(m[1]);
        if (lang && PAGES[lang] && /\\.md$/.test(path)) {
          // strip everything up to and including "/docs/" to get the page path
          var i = path.indexOf("/docs/");
          var page = path.slice(i + "/docs/".length);
          if (page.indexOf("_loc/") !== 0 && PAGES[lang].indexOf(page) !== -1) {
            var prefix = path.slice(0, i + "/docs/".length);
            arguments[1] = prefix + "_loc/" + lang + "/" + page + (qs ? "?" + qs : "");
          }
        }
      }
    } catch (e) { /* never break a request because of this shim */ }
    return open.apply(this, arguments);
  };
})();
"""
shim = shim.replace("__MANIFEST__", json.dumps(manifest, ensure_ascii=False))
with open(os.path.join(out, shim_name), "w", encoding="utf-8") as fh:
    fh.write(shim)

print(f"==> wrote {shim_name} ({sum(len(v) for v in manifest.values())} page(s), "
      f"{len(manifest)} language(s))")
PYEOF

# ------------------------------------------------------- inject into the editor pages
# Must load before pxt issues any doc request, so it goes first in <head>.
python3 - "$OUT_DIR" "$SHIM" <<'PYEOF'
import glob, os, sys

out, shim = sys.argv[1], sys.argv[2]
tag = f'<script src="/{shim}"></script>'
patched = 0
for p in glob.glob(os.path.join(out, "*.html")):
    s = open(p, encoding="utf-8", errors="ignore").read()
    if shim in s:
        continue
    i = s.lower().find("<head>")
    if i < 0:
        continue
    s = s[: i + len("<head>")] + "\n\t" + tag + s[i + len("<head>") :]
    open(p, "w", encoding="utf-8").write(s)
    patched += 1
    print(f"    injected into {os.path.basename(p)}")
print(f"==> shim injected into {patched} page(s)")
PYEOF

cat <<EOF

==> done

Switch the editor language (gear -> Language) and the docs follow. Pages without a
translation keep showing English.

Add or update a translation:
    $DOCS_SRC/<lang>/<page>.md     (mirrors docs/, e.g. de/calliope/tutorials.md)
then re-run this script.

NOTE: scripts/package_static_fetch_locs.sh starts with a rimraf of $OUT_DIR, so re-run
this script after every rebuild of the package.
EOF
